def whole_words(text, words):
    # One pass: replacing an entry must not trigger another entry by accident.
    pattern = r'(?<!\w)(?:'+'|'.join(re.escape(k) for k in sorted(words,key=len,reverse=True))+r')(?!\w)'
    return re.sub(pattern,lambda m:words[m[0]],text)

def apply(text, english):
    text=whole_words(text,WORDS)
    if 'Gardener' in english:
        text=whole_words(text,{'Садовник':'Гарденер','Садовника':'Гарденера','Садовников':'Гарденеров','Садовники':'Гарденеры','Садовником':'Гарденером'})
    if 'Reach' in english:
        forms={'Предел':'Простор','Предела':'Простора','Пределу':'Простору','Пределе':'Просторе','Пределом':'Простором'}
        def replace_reach(m):
            before=text[:m.start()].rstrip().split()
            return m[0] if before and before[-1].startswith('Штормов') else forms[m[0]]
        text=re.sub(r'\b(?:Предел|Предела|Пределу|Пределе|Пределом)\b',replace_reach,text)
    if 'Shivers' in english:
        text=whole_words(text,{'Лихорадка':'Дрожь','Лихорадки':'Дрожи','Лихорадку':'Дрожь','Лихорадкой':'Дрожью','Шиверы':'Дрожь','Шиверс':'Дрожь'})
        text=text.replace('после Дрожь','после Дрожи').replace('Дрожь сошли','Дрожь сошла')
    if 'Silverwing' in english:
        text=text.replace('на Среброкрылая','на Среброкрылую').replace('посадила Среброкрылой','посадила Среброкрылую').replace('ждут Вермитора и Среброкрылой','ждут Вермитор и Среброкрылая')
    if re.search(r'\bprogress',english,re.I):
        text=whole_words(text,{'прогресс':'объезд','прогресса':'объезда','прогрессу':'объезду','прогрессом':'объездом','прогрессе':'объезде'})
    if re.search(r'\bmatch\b',english,re.I):
        text=whole_words(text,{'матче':'браке','матч':'брак','Матч':'Брак','матча':'брака'})
    # A knight's address is "сир" in the AGOT Russian localization.
    text=re.sub(r'\b[Сс]ер(?= [А-ЯЁ])',lambda m:'Сир' if m[0][0].isupper() else 'сир',text)
    return text
